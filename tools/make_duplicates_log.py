#!/usr/bin/env python3
"""Build duplicates-log.md: the differences between the two copies of each duplicate leaf.

The scan has 16 PDF pages that repeat a printed page (see CLAUDE.md and pagelist.py). Each twin was transcribed from its own
image, never copied from the other, so every difference below is a different reading of the same printed page: a worn
glyph read two ways, a dropped or added word, or a real difference between two impressions. For each pair the log gives
the running heads and footers, the word-level differences (punctuation counts; markdown marks and comments are ignored),
and the `uncertain` / `[illegible]` marks of each copy. The combined outputs use the first copy (pagelist.SKIP lists the
twins left out); this log is where to look when the second copy reads better.

Usage:  python3 tools/make_duplicates_log.py [--out FILE]
"""
import argparse
import difflib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pagelist  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]

# (copy used in the combined outputs, twin, printed page / note)
PAIRS = [
    (147, 155, 'Jacob, p. 126'),
    (148, 156, 'Jacob, p. 127'),
    (221, 231, 'Mosiah, p. 200'),
    (229, 239, 'Mosiah, p. 208'),
    (230, 240, 'Alma, p. 209'),
    (230, 232, 'Alma, p. 209 (third copy; PDF 232 is a damaged scan written as fragments)'),
    (233, 241, 'Alma, p. 210'),
    (234, 242, 'Alma, p. 211'),
    (235, 245, 'Alma, p. 214'),
    (236, 246, 'Alma, p. 215'),
    (237, 247, 'Alma, p. 216'),
    (238, 248, 'Alma, p. 217'),
    (341, 343, 'Alma, p. 310'),
    (342, 344, 'Alma, p. 311'),
    (435, 437, 'Helaman, p. 402'),
    (436, 438, 'Helaman, p. 403'),
]


def parts(n):
    t = (pagelist.PAGES_DIR / f'page-{n:03d}.md').read_text(encoding='utf-8')
    head = re.search(r'(?m)^\*\*Header:\*\*\s*(.*)$', t)
    foot = re.search(r'(?m)^Footer:\s*(.*)$', t)
    marks = [re.sub(r'\s+', ' ', m) for m in re.findall(r'<!--\s*(uncertain.*?)\s*-->', t, flags=re.S)]
    ill = len(re.findall(r'\[illegible\]', t))
    body = re.sub(r'<!--.*?-->', ' ', t, flags=re.S)
    body = re.sub(r'(?m)^\*\*Header:\*\*.*$|^Footer:.*$|^---+\s*$', ' ', body)
    body = body.replace('*', '').replace('#', ' ').replace('[illegible]', ' ')
    words = body.split()
    clean = lambda s: re.sub(r'<!--.*?-->', '', s).strip() if s else None
    return {'head': clean(head.group(1)) if head else None, 'foot': clean(foot.group(1)) if foot else None,
            'words': words, 'marks': marks, 'ill': ill}


def diff_words(a, b):
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    out = []
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == 'equal':
            continue
        ctx = ' '.join(a[max(0, i1 - 4):i1])
        out.append((op, ' '.join(a[i1:i2]), ' '.join(b[j1:j2]), ctx))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=str(ROOT / 'duplicates-log.md'))
    args = ap.parse_args()
    lines = ['# Duplicate leaves: differences between the two copies', '',
             'Generated by `tools/make_duplicates_log.py` from the page files. The scan repeats 16 PDF pages (one printed page '
             'twice, or for Alma p. 209 three times). Each copy was transcribed from its own image and never from its twin, so '
             'each difference is a different reading of the same printed page (worn glyph, dropped or added word) or a real '
             'difference between impressions. The combined outputs use the first copy of each pair; where the second copy '
             'reads better, say so here and change the page file. Words are compared with punctuation; comments and markdown '
             'marks are ignored. `A` = the copy used, `B` = the twin skipped.', '']
    total_diffs = 0
    summary = []
    for a, b, note in PAIRS:
        pa, pb = parts(a), parts(b)
        fragment = 'damaged' in note  # PDF 232 holds only line fragments: a word diff would be noise
        diffs = [] if fragment else diff_words(pa['words'], pb['words'])
        total_diffs += len(diffs)
        summary.append((a, b, note, 'not compared (fragments)' if fragment else len(diffs)))
        lines += [f'## PDF {a} (A) vs {b} (B): {note}', '',
                  f'- Header A: `{pa["head"]}`', f'- Header B: `{pb["head"]}`'
                  + ('' if pa['head'] == pb['head'] else '  **differs**'),
                  f'- Footer A: `{pa["foot"]}` / B: `{pb["foot"]}`' + ('' if pa['foot'] == pb['foot'] else '  **differs**'),
                  f'- Words A: {len(pa["words"])}, B: {len(pb["words"])}; `[illegible]` A: {pa["ill"]}, B: {pb["ill"]}; '
                  f'uncertain marks A: {len(pa["marks"])}, B: {len(pb["marks"])}', '']
        if diffs:
            lines.append(f'Differences ({len(diffs)}):')
            lines.append('')
            for op, x, y, ctx in diffs:
                kind = {'replace': 'differs', 'delete': 'only in A', 'insert': 'only in B'}[op]
                lines.append(f'- {kind}: A `{x or "—"}` / B `{y or "—"}` (after "…{ctx}")')
            lines.append('')
        elif fragment:
            lines += ['Not compared word by word: B holds only the legible parts of the lines (see its own comments).', '']
        else:
            lines += ['No word differences.', '']
        for tag, p in (('A', pa), ('B', pb)):
            for m in p['marks']:
                lines.append(f'- uncertain in {tag}: {m}')
        lines.append('')
    head = ['', '| A | B | Page | Word differences |', '|---|---|---|---|']
    head += [f'| {a} | {b} | {note.split(" (")[0]} | {n} |' for a, b, note, n in summary]
    lines[4:4] = head + ['']
    Path(args.out).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(PAIRS)} pairs, {total_diffs} word differences -> {args.out}')


if __name__ == '__main__':
    main()
